export const searchAirportsLocal = (query) => {
  if (!query || query.trim().length === 0) return MAJOR_AIRPORTS.slice(0, 8);
  const q = query.toLowerCase().trim();

  const matches = MAJOR_AIRPORTS.filter((airport) => {
    return (
      airport.iataCode.toLowerCase().includes(q) ||
      airport.city.toLowerCase().includes(q) ||
      airport.name.toLowerCase().includes(q) ||
      airport.country.toLowerCase().includes(q) ||
      (airport.state && airport.state.toLowerCase().includes(q))
    );
  }).slice(0, 10);

  // If user typed 3 letters and it wasn't matched directly, provide it as a custom IATA airport option
  if (matches.length === 0 && q.length === 3) {
    const code = q.toUpperCase();
    matches.push({
      iataCode: code,
      name: `${code} Airport`,
      city: code,
      country: 'India / International',
      countryCode: 'IN',
      timezone: 'Asia/Kolkata',
    });
  }

  return matches;
};

export const getAirportByCode = (code) => {
  if (!code) return null;
  const upper = code.toUpperCase().trim();
  return MAJOR_AIRPORTS.find((a) => a.iataCode === upper) || {
    iataCode: upper,
    name: `${upper} Airport`,
    city: upper,
    country: 'India',
    countryCode: 'IN',
    timezone: 'Asia/Kolkata',
  };
};
